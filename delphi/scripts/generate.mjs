#!/usr/bin/env node
// Node is a maintainer dependency only; consumers need only the Delphi RTL.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const specPath = process.env.SPEC_PATH || resolve(root, 'openapi-v1.json');
const specText = readFileSync(specPath, 'utf8');
const spec = JSON.parse(specText);
const quote = s => `'${s.replaceAll("'", "''")}'`;
const identifier = s => {
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(s)) throw new Error(`Invalid Pascal identifier: ${s}`);
  return s;
};
const parameter = s => 'A' + identifier(s)[0].toUpperCase() + s.slice(1);
const declarations = [], implementations = [], seen = new Set();
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method))
      throw new Error(`Unsupported path item: ${method} ${path}`);
    const name = identifier(operation.operationId);
    if (seen.has(name.toLowerCase())) throw new Error(`Duplicate operation: ${name}`);
    seen.add(name.toLowerCase());
    const parameters = operation.parameters || [];
    if (parameters.some(p => !['path', 'query'].includes(p.in)))
      throw new Error(`Unsupported parameter: ${name}`);
    const pathParams = parameters.filter(p => p.in === 'path');
    const hasQuery = parameters.some(p => p.in === 'query');
    const requiredQuery = parameters.filter(p => p.in === 'query' && p.required);
    const contents = Object.keys(operation.requestBody?.content || {});
    const multipart = contents.includes('multipart/form-data');
    const jsonBody = contents.includes('application/json');
    if (contents.length && !(multipart || jsonBody)) throw new Error(`Unsupported body: ${name}`);
    const args = pathParams.map(p => `const ${parameter(p.name)}: string`);
    const body = [];
    const pathExpr = path.split(/(\{[^}]+\})/).filter(Boolean).map(part => {
      if (!part.startsWith('{')) return quote(part);
      const key = part.slice(1, -1);
      if (!pathParams.some(p => p.name === key)) throw new Error(`Unknown path parameter: ${key}`);
      return `PathSegment(${parameter(key)})`;
    }).join(' + ');
    if (jsonBody) {
      args.push('ABody: TJSONObject');
      body.push("  if ABody = nil then raise EArgumentException.Create('Request body is required');");
    }
    if (multipart) {
      if (name === 'UpdateCertificateCompany') {
        args.push('const ACertificateFile: string', 'const APassword: string');
        body.push(`  Result := UploadFile('PUT', ${pathExpr}, 'certificate',`,
          "    ACertificateFile, 'application/x-pkcs12',",
          "    TEcfQuery.Create(TNameValuePair.Create('password', APassword)));");
      } else if (name === 'FirmarSemilla') {
        args.push('const AXmlFile: string');
        body.push(`  Result := UploadFile('POST', ${pathExpr}, 'xml', AXmlFile,`,
          "    'application/xml', nil);");
      } else throw new Error(`Unsupported multipart operation: ${name}`);
    } else {
      if (hasQuery) args.push('const AQuery: TEcfQuery = nil');
      if (requiredQuery.length)
        body.push(`  RequireQuery(AQuery, [${requiredQuery.map(p => quote(p.name)).join(', ')}]);`);
      body.push(`  Result := RequestJson('${method.toUpperCase()}', ${pathExpr},`,
        `    ${jsonBody ? 'ABody' : 'nil'}, ${hasQuery ? 'AQuery' : 'nil'});`);
    }
    const signature = `${name}${args.length ? `(${args.join('; ')})` : ''}: ${multipart ? 'string' : 'TJSONValue'};`;
    declarations.push(`    // ${method.toUpperCase()} ${path}`, `    function ${signature}`);
    implementations.push(`function TEcfApi.${signature.replaceAll(' = nil', '')}`,
      'begin', ...body, 'end;', '');
  }
}
const output = `// Generated by scripts/generate.mjs. Do not edit this unit manually.
// OpenAPI SHA-256: ${createHash('sha256').update(specText).digest('hex')}
unit EcfDgii.Api;

interface

uses System.SysUtils, System.JSON, System.Net.URLClient, EcfDgii.Http;

type
  // JSON inputs stay caller-owned. Free each JSON result; empty responses return nil.
  // Query arrays use the exact parameter names from OpenAPI and may repeat keys.
  TEcfApi = class(TEcfHttpClient)
  public
${declarations.join('\n')}
  end;

implementation

${implementations.join('\n')}
end.
`;
const target = resolve(root, 'src/EcfDgii.Api.pas');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Generated Delphi API is stale; run scripts/generate.mjs');
  console.log(`Delphi API matches OpenAPI: ${seen.size} operations.`);
} else {
  writeFileSync(target, output);
  console.log(`Generated ${seen.size} Delphi API operations.`);
}
